// 数据库里历史遗留的写法 → 国家代码
const LEGACY_NAMES: Record<string, string> = {
  'The Netherlands': 'NL',
  Czechia: 'CZ',
  'Hong Kong SAR China': 'HK',
  'Macao SAR China': 'MO',
  'Korea': 'KR',
  'Türkiye': 'TR',
  'Myanmar (Burma)': 'MM',
}

const norm = (s: string) => s.toLowerCase().replace(/[^a-z]/g, '')

const NAME_INDEX: Record<string, string> = (() => {
  const idx: Record<string, string> = {}
  for (const [code, [name]] of Object.entries(COUNTRIES)) idx[norm(name)] = code
  for (const [name, code] of Object.entries(LEGACY_NAMES)) idx[norm(name)] = code
  return idx
})()

/** 国家代码 → 存库用的显示名；未知代码返回 null */
export function countryNameFromCode(code: string | null | undefined): string | null {
  if (!code) return null
  return COUNTRIES[code.toUpperCase()]?.[0] ?? null
}

export interface ResolvedCountry {
  code: string
  name: string
  lat: number | null
  lng: number | null
}

/** 库里存的国家名（包括旧写法）→ 统一后的国家信息；认不出来返回 null */
export function resolveCountry(name: string | null | undefined): ResolvedCountry | null {
  if (!name) return null
  const code = NAME_INDEX[norm(name)]
  if (!code) return null
  const [canonical, lat, lng] = COUNTRIES[code]
  return { code, name: canonical, lat: lat ?? null, lng: lng ?? null }
}
